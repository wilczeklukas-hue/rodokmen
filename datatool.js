// Single entry point for reading and writing web/data.js.
// Usage:
//   const T = require('./datatool');
//   const d = T.load();
//   const p = T.person(d, 'janN');
//   p.d = { date: '…', year: 1950 };
//   T.save(d);
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const FILE = path.join(__dirname, 'data.js');
const EMPTY = { root: '', lines: [], people: [], places: [], story: [], timeline: [], moves: [], events: [] };

function parse(src) {
  const sandbox = { window: {} };
  vm.runInNewContext(src, sandbox, { filename: 'data.js' });
  if (!sandbox.window.RODOKMEN) throw new Error('data.js does not define window.RODOKMEN');
  return sandbox.window.RODOKMEN;
}

function load() {
  if (!fs.existsSync(FILE)) return JSON.parse(JSON.stringify(EMPTY));
  const d = parse(fs.readFileSync(FILE, 'utf8'));
  for (const k of Object.keys(EMPTY)) if (d[k] === undefined) d[k] = JSON.parse(JSON.stringify(EMPTY[k]));
  return d;
}

function person(d, id) {
  const p = d.people.find(x => x.id === id);
  if (!p) throw new Error(`person '${id}' does not exist`);
  return p;
}

function addPerson(d, p) {
  if (!p.id) throw new Error('person without id');
  if (d.people.some(x => x.id === p.id)) throw new Error(`person '${p.id}' already exists`);
  d.people.push(p);
  return p;
}

function serialize(d) {
  return '// Generated by datatool.js – do not edit by hand.\nwindow.RODOKMEN = ' + JSON.stringify(d, null, 1) + ';\n';
}

function save(d) {
  const before = new Set(load().people.map(p => p.id));
  const src = serialize(d);
  const check = parse(src);
  if (JSON.stringify(check) !== JSON.stringify(d)) throw new Error('round-trip check failed, nothing written');
  const after = new Set(check.people.map(p => p.id));
  const lost = [...before].filter(id => !after.has(id));
  if (lost.length && !save.allowRemove) throw new Error('people would be lost: ' + lost.join(', ') + ' (set T.save.allowRemove = true to delete on purpose)');
  fs.writeFileSync(FILE + '.tmp', src);
  fs.renameSync(FILE + '.tmp', FILE);
  return check;
}

module.exports = { load, save, person, addPerson, FILE };
